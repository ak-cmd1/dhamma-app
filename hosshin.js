// 発心(サンヴェーガ)の一撃
//
// 五蓋に応じた経典が「静める」言葉であるのに対し、こちらは「突きつける」言葉。
// 現地のダンマトークで背筋が伸びるのは、なだめられるからではなく、
// こうしてはいられないと思い知らされるからである。
//
// サンヴェーガ(悚懼・厭離)は、修行を始めさせる力そのものを指す語。
// 対になるパサーダ(確信)「だが道はある」と組で働く。片方だけでは、
// 焦りか、なまぬるさのどちらかに落ちる。だからここでは、
// 突き放したまま終わらず、必ず道の側へ返す。
//
// 鐘の直前、坐へ送り出す最後の一言として読まれる。
// 長く説明しない。二〜四行で足りる。耳に残るのは短い言葉だけである。
//
// 出典はパーリ仏典。原文および経典の分類は著作権の対象外。
